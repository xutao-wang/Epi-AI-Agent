#!/usr/bin/env python3.12
"""Run one live Pro 0813 repair turn after a real partial-reference rejection.

Uses a controlled measurement table and the native model builder, context,
tool executor, artifact store and Python worker. The initial invalid call is a
deliberate test input; the subsequent tool arguments are generated by the real
provider. No arguments are filled in by this script. Model settings come from
the recorded October 29 batch. HTTP observation saves bodies, never headers.
"""
from __future__ import annotations

import argparse
from dataclasses import asdict
from datetime import UTC, datetime
import json
import os
from pathlib import Path
import signal
import sys
import tempfile
import time
import traceback

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

import httpx
from langchain_core.messages import AIMessage, HumanMessage
import pandas as pd

from epi_agent.agent import GENERAL_CORE_INSTRUCTIONS, build_epi_agent_context_prompt
from epi_agent.artifacts import StateArtifactStore
from epi_agent.protocol import ToolContext
from epi_agent.registry import ToolRegistry
from epi_agent.runtime import EpiAgentRuntimeConfig, _call_model, _execute_tools
from epi_agent.runtimes.python import LocalPythonRuntime
from epi_agent.studies import StudyRegistry
from epi_agent.tool_packs.analysis.python.tools import RunCustomPythonTool
from llm_vllm import build_chat_llm
from utils.env_loader import load_app_environment
from utils.model_runtime_profiles import CustomModelEntry


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--settings-batch", type=Path, default=REPO_ROOT.parent /
        "epi-agent-benchmark/runs/batch-20261029T144525099004Z-833434755493166-openrouter-deepseek-v4-pro-0813/batch-run.json")
    args = parser.parse_args()
    root = Path(tempfile.mkdtemp(prefix="epi-analysis-input-recovery-live-"))
    started = time.monotonic()
    result = {"status": "running", "started_at": datetime.now(UTC).isoformat(),
        "artifacts": str(root), "model_invoked": False, "model_turns": 0,
        "initial_invalid_call_injected": True, "http_requests": []}
    state = {}
    original_send = httpx.Client.send

    def timeout(*_):
        raise TimeoutError("Five-minute live smoke limit exceeded")

    def observe_send(client, request, *send_args, **send_kwargs):
        selected = request.url.host == "openrouter.ai" and request.url.path.endswith("/chat/completions")
        entry = None
        if selected:
            entry = {"sequence": len(result["http_requests"]) + 1}
            body = json.loads(request.read())
            filename = f"request-{entry['sequence']:03d}.json"
            (root / filename).write_text(json.dumps(body, indent=2) + "\n")
            entry["request_path"] = filename
            result["http_requests"].append(entry)
        response = original_send(client, request, *send_args, **send_kwargs)
        if entry is not None:
            entry["http_status"] = response.status_code
            payload = response.read().decode("utf-8")
            (root / f"response-{entry['sequence']:03d}.json").write_text(payload)
            parsed = json.loads(payload)
            entry.update({key: parsed[key] for key in ("id", "model", "provider", "usage", "error") if key in parsed})
        return response

    def apply_patch(patch):
        messages = state.get("messages", []) + patch.pop("messages", [])
        state.update(patch)
        state["messages"] = messages

    signal.signal(signal.SIGALRM, timeout)
    signal.alarm(300)
    try:
        load_app_environment(REPO_ROOT)
        recorded = json.loads(args.settings_batch.read_text())["runtime_settings"]["profile"]
        assert recorded["model_id"] == "openrouter:deepseek-v4-pro-0813"
        values = {key: recorded[key] for key in (
            "provider", "base_url", "initial_output_tokens", "automatic_output_token_ceiling",
            "user_output_token_increment", "absolute_output_token_ceiling", "request_timeout_seconds",
            "workflow_timeout_seconds", "routing_context_char_ceiling", "output_approval_required",
            "supports_sampling_controls", "supports_vision", "supports_mid_conversation_system",
        )}
        profile = CustomModelEntry(id=recorded["model_id"], model=recorded["remote_model_id"],
            label="DeepSeek V4 Pro 0813", api_key_env="OPENROUTER_API_KEY", **values).to_profile()
        assert os.getenv(profile.api_key_env), "OpenRouter credential is unavailable."
        result["profile"] = asdict(profile)
        result["settings_source"] = str(args.settings_batch)
        store = StateArtifactStore()
        source = root / "measurements.parquet"
        pd.DataFrame({"id": [1, 2, 3], "value": [2.0, 4.0, 6.0]}).to_parquet(source, index=False)
        reference = store.save_dataset({"id": "live-measurements", "kind": "subset", "version": 1,
            "status": "active", "path": str(source)}, make_active=True)
        studies = StudyRegistry()
        registry = ToolRegistry([RunCustomPythonTool(
            LocalPythonRuntime(runtime_root=root, memory_limit_bytes=None), runtime_root=root,
        )])
        config = EpiAgentRuntimeConfig(
            agent_name="epi_agent", system_prompt=GENERAL_CORE_INSTRUCTIONS,
            registry=registry, studies=studies, model_profile=profile,
            context_prompt_factory=build_epi_agent_context_prompt,
            context_factory=lambda _state, _config, artifacts: ToolContext(
                studies=studies, artifact_store=artifacts, thread_id="live-smoke", policy=None,
            ),
        )
        query = "Using the selected stored measurement table, compute the arithmetic mean of value. Use its actual records."
        code = "record_analysis_dataset(dataset, name='cohort', role='analysis_population')\nprint(dataset.value.mean())"
        partial = {"analysis_goal": query, "code": code,
            "code_summary": "Record the analysis population and calculate its mean.",
            "code_assumptions": "All three measurements are complete; no weighting is requested.",
            "dataset_source": "prior_artifact",
            "dataset_source_reason": "The selected active artifact live-measurements contains the requested records."}
        state.update(messages=[HumanMessage(content=query), AIMessage(content="", tool_calls=[{
            "name": "analysis-run_custom_python", "args": partial, "id": "initial-partial", "type": "tool_call",
        }])], artifacts=store.snapshot(), current_turn_artifact_refs=[asdict(reference)])
        runnable_config = {"configurable": {"thread_id": "live-smoke"}}
        apply_patch(_execute_tools(state, runnable_config, agent_config=config))
        error = json.loads(state["messages"][-1].content)["error"]
        assert error["code"] == "DATASET_METADATA_INCOMPLETE"
        assert error["details"]["missing_fields"] == ["dataset_id", "dataset_kind", "dataset_version"]
        result["initial_error"] = error
        model = build_chat_llm(model_name=profile.model_id, profile=profile, temperature=0.0, top_p=1.0)
        httpx.Client.send = observe_send
        result.update(model_invoked=True, model_turns=1)
        apply_patch(_call_model(state, runnable_config, agent_config=config, model=model))
        answer = state["messages"][-1]
        assert isinstance(answer, AIMessage), "The native model node did not return an AIMessage."
        result["model_response"] = answer.model_dump(mode="json")
        calls = answer.tool_calls
        assert len(calls) == 1 and calls[0]["name"] == "analysis-run_custom_python", "The model did not submit one analysis call."
        supplied = calls[0]["args"]
        result["supplied_metadata"] = {field: supplied.get(field) for field in (
            "dataset_id", "dataset_kind", "dataset_version", "dataset_source", "dataset_source_reason",
        )}
        result["python_code_unchanged"] = supplied.get("code") == code
        assert all(value is not None for value in result["supplied_metadata"].values()), "The live repair still omitted dataset fields."
        apply_patch(_execute_tools(state, runnable_config, agent_config=config))
        assert state["messages"][-1].status == "success", state["messages"][-1].content
        [run] = [a for a in StateArtifactStore.from_state(state).list_artifacts() if a.kind == "analysis_run"]
        result["analysis_output"] = run.content["output_text"].strip()
        result["analysis_input"] = run.content["dataset"]
        assert result["analysis_output"] == "4.0", result["analysis_output"]
        assert result["analysis_input"] == {"id": "live-measurements", "kind": "subset", "version": 1}
        request = json.loads((root / result["http_requests"][0]["request_path"]).read_text())
        result["error_present_in_http_request"] = any(
            message.get("role") == "tool" and json.loads(message.get("content", "{}")) == {"error": error}
            for message in request["messages"] if message.get("role") == "tool"
        )
        assert result["error_present_in_http_request"]
        assert result["python_code_unchanged"], "The model repaired metadata but also rewrote the Python code."
        result["status"] = "passed"
    except BaseException:
        result.update(status="failed", traceback=traceback.format_exc())
    finally:
        httpx.Client.send = original_send
        signal.alarm(0)
        result["duration_seconds"] = time.monotonic() - started
        (root / "state.json").write_text(json.dumps({**state,
            "messages": [message.model_dump(mode="json") for message in state.get("messages", [])],
        }, indent=2, default=str) + "\n")
        (root / "result.json").write_text(json.dumps(result, indent=2, default=str) + "\n")
        print(f"{result['status']}: {root / 'result.json'}")
    return 0 if result["status"] == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
